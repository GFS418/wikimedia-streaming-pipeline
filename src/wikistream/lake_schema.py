"""Generate the Spark schema of a landing row from the Avro contract (decision P3-2).

The .avsc stays the single source of truth: this module turns it into the Spark schema
Auto Loader reads with, `scripts/generate_landing_schema.py` writes that schema into the
pipeline folder (Databricks never reads the .avsc itself), and a drift test fails if the
committed copy no longer matches the .avsc.

Landing row (decision D12): {"kafka": {...}, "value": <Avro record>}.
"""

from __future__ import annotations

import json
from typing import Any

from pyspark.sql.types import (
    BooleanType,
    DataType,
    IntegerType,
    LongType,
    MapType,
    StringType,
    StructField,
    StructType,
)

from wikistream.contract import load_schema

PRIMITIVES: dict[str, DataType] = {
    "string": StringType(),
    "long": LongType(),
    "int": IntegerType(),
    "boolean": BooleanType(),
}

# Envelope fields written by the consumer (wikistream/consumer.py:envelope).
KAFKA_STRUCT = StructType(
    [
        StructField("topic", StringType()),
        StructField("partition", IntegerType()),
        StructField("offset", LongType()),
        StructField("timestamp_ms", LongType()),
        StructField("key", StringType()),
        StructField("schema_id", IntegerType()),
        StructField("headers", MapType(StringType(), StringType())),
    ]
)


def avro_to_spark(avro_type: Any) -> DataType:
    """Map an Avro type to Spark. Unions are only ever ["null", T] in our contract."""
    if isinstance(avro_type, list):
        non_null = [t for t in avro_type if t != "null"]
        if len(non_null) != 1:
            raise ValueError(f"unsupported union: {avro_type}")
        return avro_to_spark(non_null[0])
    if isinstance(avro_type, str):
        if avro_type not in PRIMITIVES:
            raise ValueError(f"unsupported Avro type: {avro_type}")
        return PRIMITIVES[avro_type]
    if isinstance(avro_type, dict) and avro_type.get("type") == "record":
        # File sources read every column as nullable; required-ness is enforced upstream
        # (producer contract) and re-checked in silver, not by the reader.
        return StructType(
            [StructField(f["name"], avro_to_spark(f["type"])) for f in avro_type["fields"]]
        )
    raise ValueError(f"unsupported Avro schema node: {avro_type}")


def landing_schema(avsc: dict[str, Any] | None = None) -> StructType:
    record = avro_to_spark(avsc or load_schema())
    return StructType([StructField("kafka", KAFKA_STRUCT), StructField("value", record)])


def render_module(avsc: dict[str, Any] | None = None) -> str:
    """Source of pipeline/wikistream_lake/landing_schema.py (deterministic)."""
    schema_json = json.dumps(landing_schema(avsc).jsonValue(), indent=1, sort_keys=True)
    return (
        '"""GENERATED by scripts/generate_landing_schema.py from schemas/recentchange-v1.avsc.\n'
        "\n"
        "Do not edit by hand: change the .avsc and regenerate. tests/test_lake_schema.py fails\n"
        'if this file and the .avsc disagree.\n"""\n'
        "\n"
        "import json\n"
        "\n"
        "from pyspark.sql.types import StructType\n"
        "\n"
        f"LANDING_SCHEMA_JSON = r'''{schema_json}'''\n"
        "\n"
        "LANDING_SCHEMA = StructType.fromJson(json.loads(LANDING_SCHEMA_JSON))\n"
    )
